async function main() {
  const database = process.env.TURSO_DATABASE_URL ? "remote Turso" : "local SQLite";
  const row = (await queryOne(
    "SELECT id, body_md FROM entities WHERE slug = ? AND type = 'article'",
    [SLUG],
  )) as { id: string; body_md: string | null } | undefined;

  if (!row?.body_md) {
    throw new Error(`Missing article body for ${SLUG}`);
  }

  const nextBody = row.body_md.replace(
    /约\s*\n\n\[内容已截断\]\s*$/,
    CONTINUATION,
  );

  if (nextBody === row.body_md) {
    console.log(JSON.stringify({ database, changed: false, reason: "no truncation marker" }, null, 2));
    return;
  }

  await execute(
    `UPDATE entities
     SET body_md = ?,
         updated_at = datetime('now')
     WHERE id = ?`,
    [nextBody, row.id],
  );

  console.log(
    JSON.stringify(
      {
        database,
        changed: true,
        previousLength: row.body_md.length,
        nextLength: nextBody.length,
        removedTruncationMarker: !nextBody.includes("[内容已截断]"),
      },
      null,
      2,
    ),
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
