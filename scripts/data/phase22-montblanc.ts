function researchSource(
  source: Omit<CuratedSource, "retrievedAt" | "allowedUse" | "archiveUrl" | "archiveLocator"> & {
    researchFile: keyof typeof RESEARCH_EVIDENCE_SNAPSHOTS;
    researchKey: string;
    sourceArchiveUrl?: string;
    sourceArchiveLocator?: string;
  },
): CuratedSource {
  const {
    researchFile,
    researchKey,
    sourceArchiveUrl,
    sourceArchiveLocator,
    ...record
  } = source;
  const evidenceSnapshotUrl = RESEARCH_EVIDENCE_SNAPSHOTS[researchFile];
  return {
    ...record,
    retrievedAt: RETRIEVED,
    allowedUse: record.sourceType === "wikimedia" ? "store_full" : "summary_only",
    archiveUrl: sourceArchiveUrl ?? evidenceSnapshotUrl,
    archiveLocator:
      sourceArchiveLocator ??
      `project-evidence-snapshot:${evidenceSnapshotUrl}#${researchKey};raw_source_stored=false;external_archive=false`,
  };
}

